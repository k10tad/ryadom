const crisis = /(死にたい|消えたい|自殺|自傷|傷つけたい|生きていたくない|終わりにしたい)/;
let sequence = 0;

export function emotionalSupportFromMessage(rawText) {
  const text = String(rawText || '').normalize('NFKC').trim();
  if (!text) return null;
  if (crisis.test(text)) return { kind: 'emotional-care', urgent: true, text: 'そこまで追い詰められてるんだね。今、自分を傷つける手段が手元にある、または今すぐ実行しそう？ もし「ある／しそう」なら、ひとりにならず119へ電話して、危険な物から離れて。差し迫っていなくても、信頼できる人か、こころの健康相談統一ダイヤル0570-064-556につないでほしい。返事は「今すぐ危険」か「今は安全」の二つだけでもいい。' };
  const hit = categories.find(([, pattern]) => pattern.test(text));
  if (!hit) return null;
  const list = responses[hit[0]] || responses.general;
  const reply = list[sequence++ % list.length];
  return { kind: 'emotional-care', urgent: false, text: reply };
}
